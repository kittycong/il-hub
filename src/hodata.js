/* ===== 절차 목록 (기본 + 화면에서 고친 것 + 직접 만든 것) ===== */
function sops() {
  const ed = S.hoEdit || {}, custom = S.hoCustom || [];
  return [...HO_SOPS.map(s => ed[s.id] ? Object.assign({}, s, ed[s.id], {edited:true}) : s), ...custom.map(s => Object.assign({custom:true, systems:[], paths:[], rules:[]}, s))];
}
function sopById(id) { return sops().find(s => s.id === id); }
function sopOfRule(rule) { return rule.sop ? sopById(rule.sop) : sops().find(s => (s.rules || []).includes(rule.id)); }
// 절차 ↔ 편집용 글 형식
function sopToText(s) { return s.sections.map(sec => `## ${sec.h}\n` + sec.steps.map(t => `- ${t}`).join('\n') + (sec.warn || []).map(w => `\n! ${w}`).join('')).join('\n\n'); }
function textToSections(txt) {
  const out = []; let cur = null;
  txt.split('\n').forEach(l => { const t = l.trim(); if (!t) return;
    if (t.startsWith('##')) { cur = {h: t.replace(/^#+\s*/, ''), steps: [], warn: []}; out.push(cur); return; }
    if (!cur) { cur = {h: '절차', steps: [], warn: []}; out.push(cur); }
    if (t.startsWith('!')) cur.warn.push(t.replace(/^!\s*/, '')); else cur.steps.push(t.replace(/^[-·•*]\s*/, '')); });
  return out.filter(s => s.steps.length || s.warn.length);
}

